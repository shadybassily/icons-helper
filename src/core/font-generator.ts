import { Buffer } from 'buffer';
import svg2ttf from 'svg2ttf';
import svgpath from 'svgpath';
import ttf2woff from 'ttf2woff';
import { describeSelection } from './selection';
import { DEMO_CSS, DEMO_JS, READ_ME, demoHtml } from './templates/demo';
import { formatSelectionJson } from './templates/selection-json';
import { styleCss, styleScss, variablesScss, type StyleGlyph, type StyleOptions } from './templates/styles';
import type { FontPref, IcoMoonSelection } from './types';

export interface GenerateOptions {
  /** The `?xxxxxx` suffix on font URLs; random when omitted. */
  cacheBuster?: string;
  /** Unix seconds for the TTF creation date (for reproducible output). */
  timestamp?: number;
}

/** File contents keyed by path relative to the icons-font folder. */
export type IconsFontFiles = Record<string, string | Uint8Array>;

export function randomCacheBuster(): string {
  const alphabet = 'abcdefghijklmnopqrstuvwxyz0123456789';
  const bytes = crypto.getRandomValues(new Uint8Array(6));
  return Array.from(bytes, (b) => alphabet[b! % alphabet.length]).join('');
}

function escapeAttr(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function fontMetrics(prefs: FontPref) {
  const emSize = prefs.metrics.emSize;
  const descent = Math.round((emSize * prefs.metrics.baseline) / 100);
  return { emSize, descent, ascent: emSize - descent };
}

function fontVersion(prefs: FontPref): string {
  return `Version ${prefs.metadata.majorVersion ?? 1}.${prefs.metadata.minorVersion ?? 0}`;
}

function spaceAdvance(prefs: FontPref, emSize: number): number {
  const whitespace = typeof prefs.metrics.whitespace === 'number' ? prefs.metrics.whitespace : 50;
  return Math.round((emSize * whitespace) / 100);
}

/** Converts y-down em-grid paths (selection.json) into one y-up glyph outline. */
export function glyphOutline(paths: string[], ascent: number): string {
  return svgpath(paths.join('')).scale(1, -1).translate(0, ascent).round(3).toString();
}

export function buildSvgFont(selection: IcoMoonSelection, { includeMetadata = true } = {}): string {
  const prefs = selection.preferences.fontPref;
  const family = prefs.metadata.fontFamily;
  const { emSize, ascent, descent } = fontMetrics(prefs);

  const meta: Record<string, unknown> = {
    fontFamily: family,
    majorVersion: prefs.metadata.majorVersion ?? 1,
    minorVersion: prefs.metadata.minorVersion ?? 0,
  };
  if (prefs.metadata.fontURL) meta.fontURL = prefs.metadata.fontURL;
  Object.assign(meta, {
    version: fontVersion(prefs),
    fontId: family,
    psName: family,
    subFamily: 'Regular',
    fullName: family,
    description: 'Font generated by IcoMoon.',
    manufacturer: 'IcoMoon.io',
  });
  const metadata = includeMetadata
    ? `<metadata>\n<json>\n<![CDATA[\n${JSON.stringify(meta, null, '\t')}\n]]>\n</json>\n</metadata>\n`
    : '';

  const glyphs = [...selection.icons]
    .sort((a, b) => a.properties.code - b.properties.code)
    .map((icon) => {
      const width = icon.icon.width;
      const adv = width !== undefined && width !== emSize ? ` horiz-adv-x="${width}"` : '';
      const tags = escapeAttr((icon.icon.tags ?? [icon.properties.name]).join(', '));
      return (
        `<glyph unicode="&#x${icon.properties.code.toString(16)};" glyph-name="${escapeAttr(icon.properties.name)}"` +
        ` data-tags="${tags}"${adv} d="${glyphOutline(icon.icon.paths, ascent)}" />\n`
      );
    })
    .join('');

  return (
    `<?xml version="1.0" standalone="no"?>\n` +
    `<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd" >\n` +
    `<svg xmlns="http://www.w3.org/2000/svg">\n` +
    metadata +
    `<defs>\n` +
    `<font id="${escapeAttr(family)}" horiz-adv-x="${emSize}">\n` +
    `<font-face units-per-em="${emSize}" ascent="${ascent}" descent="${-descent}" />\n` +
    `<missing-glyph horiz-adv-x="${emSize}" />\n` +
    `<glyph unicode="&#x20;" horiz-adv-x="${spaceAdvance(prefs, emSize)}" d="" />\n` +
    glyphs +
    `</font></defs></svg>`
  );
}

export function buildTtf(selection: IcoMoonSelection, timestamp?: number): Uint8Array {
  const prefs = selection.preferences.fontPref;
  const family = prefs.metadata.fontFamily;
  const ttf = svg2ttf(buildSvgFont(selection, { includeMetadata: false }), {
    familyname: family,
    fullname: family,
    id: family,
    description: 'Font generated by IcoMoon.',
    url: prefs.metadata.fontURL ?? 'https://icomoon.io',
    version: fontVersion(prefs),
    ...(timestamp !== undefined ? { ts: timestamp } : {}),
  });
  return ttf.buffer;
}

export function buildWoff(ttf: Uint8Array): Uint8Array {
  return ttf2woff(Buffer.from(ttf));
}

export function styleGlyphs(selection: IcoMoonSelection): StyleGlyph[] {
  return selection.icons.map((icon) => ({ name: icon.properties.name, hex: icon.properties.code.toString(16) }));
}

/** Generates every file of an IcoMoon "icons-font" export from a selection. */
export function generateIconsFont(selection: IcoMoonSelection, opts: GenerateOptions = {}): IconsFontFiles {
  const prefs = selection.preferences.fontPref;
  const family = prefs.metadata.fontFamily;
  const glyphs = styleGlyphs(selection);
  const styleOpts: StyleOptions = {
    prefix: prefs.prefix,
    fontFamily: family,
    cacheBuster: opts.cacheBuster ?? randomCacheBuster(),
    glyphs,
  };
  const ttf = buildTtf(selection, opts.timestamp);

  return {
    'style.css': styleCss(styleOpts),
    'style.scss': styleScss(styleOpts),
    'variables.scss': variablesScss(styleOpts),
    'selection.json': formatSelectionJson(selection),
    'demo.html': demoHtml({
      prefix: prefs.prefix,
      fontFamily: family,
      gridSize: describeSelection(selection).defaultGrid,
      glyphs,
    }),
    'demo-files/demo.css': DEMO_CSS,
    'demo-files/demo.js': DEMO_JS,
    'Read Me.txt': READ_ME,
    [`fonts/${family}.svg`]: buildSvgFont(selection),
    [`fonts/${family}.ttf`]: ttf,
    [`fonts/${family}.woff`]: buildWoff(ttf),
  };
}
